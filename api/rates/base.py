"""Точка расширения: откуда берутся курсы валют.

Протокол намеренно спрашивает **все** котировки одной базы на один день, а не
курс одной пары. Так устроен выбранный источник — файл базовой валюты содержит
котировки ко всем остальным, — и так же устроена потребность: одна и та же
операция приводится и к валюте счёта (для остатка), и к валюте статистики,
то есть двух курсов одной базы за один день нужно два, а похода хватает одного.

Весь ввод-вывод собран здесь. Разбор ответа вынесен в чистую функцию рядом с
реализацией, чтобы проверяться таблицей примеров без сети.
"""

from __future__ import annotations

from datetime import date
from decimal import Decimal
from typing import Protocol, runtime_checkable

from api.enums import Currency
from api.exceptions import ExternalServiceError


class RateUnavailableError(ExternalServiceError):
    """Курс получить не удалось.

    Наследуется от :class:`~api.exceptions.base.ExternalServiceError`, то есть
    едет наружу как 502. Это осознанный выбор в пользу «лучше не показать
    ничего, чем показать неправду»: подсчёт остатка падает, задача перерисовки
    листа не отмечается выполненной и повторяется по своему расписанию, а в
    таблице до тех пор остаются прежние — верные — числа.

    Альтернатива «взять ближайший известный курс» отвергнута: она даёт число,
    неотличимое на вид от правильного, и молчаливо. Ошибка видна, тихо неверный
    остаток — нет.
    """

    code = "rate_unavailable"


