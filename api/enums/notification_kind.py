"""Повод для сообщения пользователю из фоновой работы."""

from __future__ import annotations

from enum import StrEnum


class NotificationKind(StrEnum):
    """Что произошло в фоне, пока пользователь не смотрел.

    Уведомление нужно потому, что после разделения на сервисы у фоновой работы
    не осталось способа ответить пользователю синхронно. Старый `/sync` читал
    лист и тут же возвращал текст ошибки в ответ на команду; теперь лист читает
    отдельный сервис через очередь, и ошибка разбора рождается в момент, когда
    HTTP-запроса пользователя уже нет.
    """

    #: Google-документ создан, можно давать ссылку.
    TABLE_READY = "TABLE_READY"
    #: Разбор листа не удался, в БД ничего не записано.
    IMPORT_ERROR = "IMPORT_ERROR"
    #: Перерисовка листа не удаётся раз за разом.
    SYNC_FAILED = "SYNC_FAILED"
    #: Начался новый расчётный период.
    ROLLOVER = "ROLLOVER"
