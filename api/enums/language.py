"""Язык, на котором бот говорит с пользователем."""

from __future__ import annotations

from enum import StrEnum


class Language(StrEnum):
    """Язык интерфейса бота.

    Значения совпадают с именами членов по тому же правилу, что у всех
    перечислений api: SQLAlchemy пишет в нативный enum имя, а не значение.
    Коды — ISO 639-1 в верхнем регистре; наружу, в имена каталогов и в Babel,
    их переводит в нижний регистр бот.

    Api самих текстов не знает вовсе — весь текст пользователю живёт в боте.
    Язык хранится здесь затем, что это свойство человека, а не процесса бота:
    он должен пережить перезапуск, отвязку таблицы и быть известен тем, кто
    пишет пользователю не из бота, — Mini App и уведомлениям.

    Список закрыт и меняется вместе с миграцией и каталогом бота.
    """

    RU = "RU"
    EN = "EN"
    HI = "HI"
    ES = "ES"
    FR = "FR"
