"""Состояние учётного периода."""

from __future__ import annotations

from enum import StrEnum


class PeriodStatus(StrEnum):
    """Открыт ли период для новых операций.

    Период закрывается ролловером при переходе на следующий. Закрытие —
    отдельный факт со своей меткой времени, а не просто «начало сдвинулось»:
    именно отсутствие такого факта в старой версии делало ролловер
    неповторяемым после сбоя.
    """

    OPEN = "OPEN"
    CLOSED = "CLOSED"
