"""Что именно спрашивали у модели."""

from __future__ import annotations

from enum import StrEnum


class LlmOperation(StrEnum):
    """Вид обращения к модели.

    Разбор чека спрашивает модель дважды и о разном: сначала тип товара по
    названию позиции, затем категорию по типу. Это два отдельных вызова с
    разными промптами и разной ценой, и складывать их в одну строку учёта
    значило бы потерять единственное различие, ради которого учёт и ведётся, —
    на что уходят деньги.

    Значение — нативный enum PostgreSQL, поэтому новый вид обращения требует
    миграции с `ALTER TYPE`. Это сознательный размен: опечатка в строке тихо
    развалила бы статистику на два вида, каждый из которых выглядел бы
    настоящим.
    """

    SUGGEST_PRODUCT_TYPES = "SUGGEST_PRODUCT_TYPES"
    SUGGEST_CATEGORIES = "SUGGEST_CATEGORIES"
