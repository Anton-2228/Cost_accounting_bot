"""Формат фискального чека."""

from __future__ import annotations

from enum import StrEnum


class CheckKind(StrEnum):
    """Откуда чек и по каким правилам читается его сырьё.

    Формат — свойство самого чека, а не документа и не пользователя: один и тот
    же человек в поездке отсканирует и российский, и сербский. Поэтому вид
    хранится строкой рядом с сырьём, а не выводится из настроек.

    В `external_key` каждый формат кладёт своё: для ФНС это «ФН:ФД:ФП», для
    сербского — номер чека «Затражио-Потписао-Бројач». БД про состав ключа не
    знает ничего — она лишь запрещает два одинаковых ключа одного вида в одном
    документе.
    """

    RU_FNS = "RU_FNS"
    SRB_SUF = "SRB_SUF"
