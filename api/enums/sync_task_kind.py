"""Направление задачи очереди листов."""

from __future__ import annotations

from enum import StrEnum


class SyncTaskKind(StrEnum):
    """Куда течёт информация по этой задаче.

    `REDRAW` — БД → лист: лист устарел и подлежит перерисовке из текущего
    состояния БД. Таких задач подавляющее большинство, их ставит каждая мутация.

    `IMPORT` — лист → БД: пользователь правил `Categories` или `Bills` руками и
    попросил вчитать правки (старая команда `/sync`). Api в Google не ходит, а
    у бота нет доступа к Google API, поэтому просьба доезжает до
    `google_sheets_service` единственным доступным каналом — этой же очередью.

    Направление входит в уникальный ключ задачи: перерисовка и импорт одного и
    того же листа — разные работы, схлопывать их в одну строку нельзя. Какие
    адресаты допустимы для `IMPORT`, задаёт ограничение `ck_sheet_sync_tasks_
    import_target` в :class:`api.orm.sheet_sync_task.SheetSyncTaskORM`.
    """

    REDRAW = "REDRAW"
    IMPORT = "IMPORT"
