"""Статус справочной сущности: участвует ли она в подборе по псевдонимам."""

from __future__ import annotations

from enum import StrEnum


class EntityStatus(StrEnum):
    """Активность категории или источника.

    Значения намеренно совпадают с именами членов: SQLAlchemy записывает в
    нативный enum PostgreSQL именно имя, и расхождение имени со значением
    порождает целый класс ошибок «в БД лежит COST, а в коде cost».

    Здесь **нет** члена `DELETED`. В старой схеме один enum `status_types`
    совмещал «скрыто из подбора» и «удалено», из-за чего удалённая категория
    выпадала из статистики, но её операции продолжали двигать баланс. Удаление
    выражается отдельной колонкой `deleted_at`.
    """

    ACTIVE = "ACTIVE"
    INACTIVE = "INACTIVE"
