"""Валюта денежной суммы."""

from __future__ import annotations

from enum import StrEnum


class Currency(StrEnum):
    """Валюта счёта и валюта операции.

    Значения намеренно совпадают с именами членов: SQLAlchemy записывает в
    нативный enum PostgreSQL именно имя, и расхождение имени со значением
    порождает целый класс ошибок «в БД RUB, а в коде rub».

    Коды по ISO 4217, потому что курсы приходят от внешнего источника именно по
    ним, а не по названиям. `RSD` — сербский динар: динаров в мире несколько, и
    только код различает их без двусмысленности.

    Список закрыт и меняется вместе с миграцией: он же выступает содержимым
    выпадающего списка в колонке `Currency` листа `Bills`.
    """

    RUB = "RUB"
    USD = "USD"
    EUR = "EUR"
    RSD = "RSD"
