"""Сообщение пользователю: код и параметры вместо готового текста."""

from __future__ import annotations

from pydantic import BaseModel, ConfigDict


class UserMessage(BaseModel):
    """Что сказать пользователю — без того, как это сказать.

    Api не знает ни одного текста для людей: текст зависит от языка
    пользователя, а каталоги языков живут в боте. Поэтому фоновая работа
    откладывает не фразу, а её код и данные для подстановки — номер строки
    листа, адрес почты, дату начала периода, — и фразу на нужном языке по ним
    собирает бот.

    Значения параметров — строки и целые: они уезжают в JSONB и в тело push-а.
    Дата пишется в ISO, а не в формате какой-то страны: как её показать,
    решает бот по языку пользователя.
    """

    model_config = ConfigDict(frozen=True)

    code: str
    params: dict[str, str | int] = {}
