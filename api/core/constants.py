"""Неизменяемые поведенческие константы приложения.

Единственный источник истины для значений, НЕ зависящих от окружения. Параметры
развёртывания (подключение к Postgres, уровень логирования) задаются через
окружение — см. :mod:`api.core.config` и `env/api.env.example`.
"""

from __future__ import annotations

# ---- Денежные значения (часть контракта схемы БД: Numeric(14, 2)) ----
MONEY_MAX_DIGITS = 14
MONEY_DECIMAL_PLACES = 2

# ---- Стоимость обращения к модели (часть контракта схемы БД: Numeric(18, 10)) ----
# Своя точность, а не `MONEY`: один вызов стоит доли цента, и два знака после
# запятой округлили бы каждую строку учёта в ноль.
LLM_COST_MAX_DIGITS = 18
LLM_COST_DECIMAL_PLACES = 10

# ---- Учётный период ----
# День сброса ограничен 28-м числом намеренно: только так `date.replace(day=...)`
# и сдвиг на месяц вперёд всегда дают существующую дату (31 февраля не бывает).
MIN_RESET_DAY = 1
MAX_RESET_DAY = 28

# Часовой пояс таблицы по умолчанию (IANA).
DEFAULT_TIMEZONE = "Europe/Moscow"

# ---- Пагинация ----
DEFAULT_PAGE_LIMIT = 50
MIN_PAGE_LIMIT = 1
MAX_PAGE_LIMIT = 500
DEFAULT_PAGE_OFFSET = 0

# ---- Очередь перерисовки листов (outbox) ----
# Сколько задач воркер забирает за один тик.
SHEET_SYNC_CLAIM_LIMIT = 20
# Экспоненциальная пауза перед повтором: base * 2**attempts, но не больше максимума.
SHEET_SYNC_RETRY_BASE_SECONDS = 5
SHEET_SYNC_RETRY_MAX_SECONDS = 15 * 60
# После стольких неудач подряд пользователю уходит уведомление: дальше повторы
# продолжатся, но молчать уже нельзя — таблица перестала обновляться.
SHEET_SYNC_ALERT_ATTEMPTS = 5
# Срок аренды забранной задачи. Захват снимают `complete`, `release` и `fail`,
# но воркер может не дожить ни до одного из них — умереть между `claim` и
# отчётом. Без срока такая задача осталась бы `claimed_at IS NOT NULL` навсегда,
# и лист замер бы молча: уведомление о неудаче шлёт `fail`, которого не будет.
# Значение с большим запасом перекрывает самую долгую работу — перерисовку
# документа целиком.
SHEET_SYNC_LEASE_SECONDS = 5 * 60
# Пауза после терминальной ошибки: файл удалён, доступ отозван, лист не найден.
# Повторять такое каждые несколько секунд бессмысленно — ответ Google не
# изменится, пока пользователь не вмешается. Но и снимать задачу нельзя: доступ
# могут вернуть, и тогда лист обязан догнать сам.
SHEET_SYNC_TERMINAL_RETRY_SECONDS = 60 * 60

# ---- Фоновый ролловер ----
# Пауза между проходами. Ролловер идемпотентен, поэтому лишний проход безвреден.
ROLLOVER_INTERVAL_SECONDS = 60
# Пространство имён рекомендательной блокировки (первый аргумент парной формы
# `pg_try_advisory_xact_lock(int, int)`; второй — id документа). Блокировка
# транзакционная: она снимается вместе с транзакцией и поэтому не может остаться
# висеть, если процесс умер посреди прохода. Смысл — не дать двум воркерам
# сменить месяц одному документу одновременно; ролловер от этого перестаёт
# требовать «api строго в один воркер».
ROLLOVER_ADVISORY_LOCK_NAMESPACE = 4207

# ---- Рассылка уведомлений в бота ----
# Пауза между проходами очереди `user_notifications`. Проход дешёвый: один
# запрос с join'ом по частичному индексу недоставленных.
NOTIFICATION_PUSH_INTERVAL_SECONDS = 15
# Сколько сообщений уходит за один проход. Ограничение — не про нагрузку, а про
# лимит Telegram на частоту отправки: остаток разошлётся следующим проходом.
NOTIFICATION_PUSH_LIMIT = 50
# Таймаут запроса к боту. Бот только кладёт сообщение в Telegram и отвечает,
# поэтому долго это длиться не может, а зависший запрос задержал бы всю очередь.
NOTIFICATION_PUSH_TIMEOUT_SECONDS = 10.0

# ---- Категории по умолчанию ----
# Создаются вместе с документом. Названия и поведение унаследованы: в
# `НеопределенныеТраты` складывается всё, что не удалось разложить, и типы
# товаров ей не назначаются никогда — иначе корзина «обучилась» бы на случайных
# позициях чека и начала притягивать их к себе.
DEFAULT_INCOME_CATEGORY = "НеопределенныйДоход"
DEFAULT_EXPENSE_CATEGORY = "НеопределенныеТраты"

# ---- Ограничения длины строковых полей ----
TITLE_MAX_LENGTH = 64
SPREADSHEET_TITLE_MAX_LENGTH = 255
GOOGLE_SPREADSHEET_ID_MAX_LENGTH = 128
GOOGLE_SHEET_TITLE_MAX_LENGTH = 255
EMAIL_MAX_LENGTH = 320
TIMEZONE_MAX_LENGTH = 64
NOTES_MAX_LENGTH = 512
PRODUCT_NAME_MAX_LENGTH = 255
PRODUCT_TYPE_MAX_LENGTH = 64
