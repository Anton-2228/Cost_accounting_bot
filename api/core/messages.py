"""Тексты уведомлений пользователю.

Второе и последнее место в api, где живёт русский текст (первое —
:mod:`api.validation`). Причина та же: сообщение рождается в фоновой работе, у
которой нет HTTP-ответа, и собирается из данных документа. Бот печатает его как
есть, не переводя код ошибки.

Обычные ошибки API сюда не относятся: они едут кодом (`code`), и текст для них
подбирает бот.
"""

from __future__ import annotations

from datetime import date

#: Ссылка на документ. Бот получает готовое сообщение и не собирает URL сам.
GOOGLE_SPREADSHEET_URL = "https://docs.google.com/spreadsheets/d/{google_spreadsheet_id}"

#: Названия листов, которые читаются обратно в базу. Они попадают в текст
#: сообщения, поэтому лежат здесь: раскладку документа api не знает и знать не
#: должен, а вот назвать пользователю вкладку, о которой идёт речь, обязан.
CATEGORIES_SHEET_TITLE = "Categories"
BILLS_SHEET_TITLE = "Bills"


def table_ready(google_spreadsheet_id: str) -> str:
    """Google-документ создан и готов к работе."""
    url = GOOGLE_SPREADSHEET_URL.format(google_spreadsheet_id=google_spreadsheet_id)
    return f"Таблица готова: {url}"


def import_ok(sheet_title: str) -> str:
    """Лист прочитан, правки применены.

    Сообщение уходит и тогда, когда импорт ничего не изменил. Пользователь
    правил лист и ждёт ответа; молчание при «ноль создано, ноль обновлено» он
    прочитает как «меня не услышали» — ровно та неопределённость, ради которой
    уведомление и заводится.
    """
    return f"Лист «{sheet_title}» прочитан, правки сохранены"


def rollover_done(start_date: date) -> str:
    """Начался новый расчётный период."""
    return f"Начался новый расчётный период с {start_date}"


def sync_failed(attempts: int) -> str:
    """Перерисовка листа не удаётся раз за разом."""
    return (
        f"Не удаётся обновить таблицу, попыток подряд: {attempts}. "
        "Проверьте, что доступ к документу не отозван."
    )


def sync_terminal(error: str) -> str:
    """Перерисовка невозможна, пока пользователь не вмешается.

    Текст ошибки идёт целиком: он приходит от Google и объясняет причину точнее,
    чем любая наша формулировка. Само сообщение — не «всё пропало»: задача
    осталась в очереди и выполнится, как только препятствие исчезнет.
    """
    return (
        f"Таблицу не удалось обновить: {error}. "
        "Проверьте, что документ не удалён и доступ к нему не отозван — "
        "после этого таблица обновится сама."
    )


def access_failed(email: str) -> str:
    """Google отказался выдать доступ на эту почту."""
    return (
        f"Не удалось открыть доступ к таблице для {email}. "
        "Проверьте адрес и добавьте его заново."
    )
