"""Нормализация текстовых наборов предметной области."""

from __future__ import annotations

from collections.abc import Iterable


def normalize_terms(values: Iterable[str]) -> list[str]:
    """Приводит набор псевдонимов или типов товаров к каноническому виду.

    Нижний регистр, без пустых, без дублей, отсортировано.

    Правило живёт здесь, а не в репозитории, потому что это инвариант самих
    данных: `CHECK` в дочерних таблицах не пропустит ненормализованное значение
    никаким путём, а путей записи несколько (создание, обновление, замена
    набора). Применяется валидатором доменных моделей, поэтому нормализованными
    оказываются любые псевдонимы, откуда бы они ни пришли.

    Сортировка не косметика: прежний код дедуплицировал набор через `set()`, а
    хеш строк в Python рандомизирован при каждом запуске процесса — из-за этого
    лист `Categories` перетасовывался при каждой синхронизации, и пользователь
    не мог понять, изменилось что-нибудь или нет.
    """
    return sorted({value.strip().lower() for value in values if value.strip()})
