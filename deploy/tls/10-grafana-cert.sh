#!/bin/sh
# Выпускает самоподписанный сертификат для nginx перед Grafana. Штатно
# запускается сам — одноразовым сервисом `grafana-tls-init` из
# docker-compose.yml, перед стартом `grafana-proxy`.
#
# Зачем вообще сертификат на хосте: Proxmox пробрасывает 41142 порт-в-порт
# (DNAT), шифрованное соединение идёт насквозь от браузера до этой машины, и
# снять TLS по дороге некому. Сертификат самоподписанный, потому что публичный
# CA не выдаёт сертификаты на приватные адреса, а настоящий сертификат домена
# живёт на шлюзе и обслуживает его 443-й порт.
#
# Скрипт идемпотентен и прогоняется при каждом `docker compose up -d`. Заново
# выпускает только в трёх случаях: файлов нет, сертификат протухает в ближайший
# месяц, или изменился список имён в GRAFANA_TLS_SAN. Последнее — ради переезда:
# развернули стек на другом сервере, поправили адрес в .env, и сертификат
# пересобрался сам, без единой ручной команды.
#
# Образ — postgres:16, тот же, что у базы: нужен только openssl, а тянуть ради
# него отдельный образ незачем — на серверах за блокировками каждый новый образ
# это отдельный риск не собраться.
set -eu

CERT_DIR=/etc/ssl/grafana
CERT="$CERT_DIR/grafana.crt"
KEY="$CERT_DIR/grafana.key"
# Слепок списка имён: сам сертификат печатает SAN в своём формате
# («DNS:..., IP Address:...»), сравнивать с ним строку из .env было бы гаданием.
SAN_STAMP="$CERT_DIR/.san"

SAN="${GRAFANA_TLS_SAN:?GRAFANA_TLS_SAN не задан — без имён сертификат бесполезен}"
CN="${GRAFANA_PUBLIC_HOST:?GRAFANA_PUBLIC_HOST не задан}"

need_new=""

if [ ! -f "$CERT" ] || [ ! -f "$KEY" ]; then
    need_new="сертификата ещё нет"
# -checkend 2592000: протухает в ближайшие 30 дней. Проверка именно здесь, а не
# в мониторинге: протухший сертификат закрывает единственный вход в Grafana, а
# перевыпуск стоит секунды и происходит на ближайшем перезапуске стека.
elif ! openssl x509 -in "$CERT" -noout -checkend 2592000 >/dev/null 2>&1; then
    need_new="сертификат истекает в ближайший месяц"
elif [ "$(cat "$SAN_STAMP" 2>/dev/null || echo '')" != "$SAN" ]; then
    need_new="изменился список имён (GRAFANA_TLS_SAN)"
fi

if [ -z "$need_new" ]; then
    echo "Сертификат на месте и актуален: $(openssl x509 -in "$CERT" -noout -enddate)"
    exit 0
fi

echo "Выпускаю сертификат — $need_new."

mkdir -p "$CERT_DIR"

# 10 лет: смысл этого сертификата — шифрование канала, а не доверие (браузер
# всё равно спросит подтверждение один раз на устройство). Короткий срок дал бы
# только шанс однажды упереться в протухший вход.
openssl req -x509 -newkey rsa:2048 -nodes -days 3650 \
    -subj "/CN=$CN" \
    -addext "subjectAltName=$SAN" \
    -keyout "$KEY" -out "$CERT" 2>/dev/null

# Ключ читает nginx в соседнем контейнере, работающий не от root; том общий,
# поэтому права ставятся здесь. 644 на сертификат — он публичный по природе.
chmod 640 "$KEY"
chmod 644 "$CERT"
# nginx:alpine запускает рабочие процессы от uid 101 (nginx). Мастер-процесс
# читает ключ ещё от root, до смены пользователя, поэтому 640 хватает — но
# группу выставляем на всякий случай, если образ однажды начнёт читать позже.
chgrp 101 "$KEY" 2>/dev/null || true

printf '%s' "$SAN" > "$SAN_STAMP"

echo "Готово: CN=$CN, SAN=$SAN"
openssl x509 -in "$CERT" -noout -enddate
