"""Типизированные ошибки обращения к модели.

Две штуки, и различие между ними не косметическое. `AiUnavailableError` —
внешняя причина: сеть, таймаут, отказ провайдера. `AiResponseError` — ответ
пришёл, но он не той формы, о которой договаривались.

Пользователю обе показываются одинаково («подсказки недоступны»), а вот в
журнале различаются: первую чинит время, вторую — правка промпта или схемы.
Смешать их значило бы потерять единственный сигнал о том, что модель начала
отвечать иначе.
"""

from __future__ import annotations


class AiError(Exception):
    """Подсказки у модели получить не удалось."""


class AiUnavailableError(AiError):
    """Модель недоступна: сеть, таймаут, отказ провайдера."""


class AiResponseError(AiError):
    """Ответ модели не разобрать: не JSON или JSON не той формы.

    Отдельный класс, потому что это и есть та ошибка, на которой ветка чеков
    разваливалась в старой версии: `for x, id in answer:` по словарю давал
    `ValueError` мимо обработчика, и пользователь не получал ничего. Форма
    ответа теперь проверяется схемой, а несовпадение становится ошибкой с
    именем.
    """
