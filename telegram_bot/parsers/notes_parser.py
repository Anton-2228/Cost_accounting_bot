"""Разбор пометки — текста, который ляжет в `notes` операции.

Формата у пометки нет: ею становится присланное сообщение целиком. Разбирать
тут, казалось бы, нечего — но правил, которым она обязана подчиняться, три, и
нужны они в двух местах сразу: хвосту `/add` и стадии пометки в разборе чека.
Оставленные по месту, они разъехались бы — как разъезжаются всегда две копии
одного правила, — и разъехались бы незаметно: отказ сработал бы в одной команде
и промолчал в другой.

Одна строка, потому что блок стадии — одно сообщение: название этапа, тело и
клавиатура. Пометка в десять строк растянула бы его так, что кнопки уехали бы
за край экрана, а сама она в листе операций всё равно легла бы в одну ячейку.

Отдельный парсер, а не форма :class:`~telegram_bot.parsers.CheckParser`: у того
каждая строка — правка позиции, и «молочка» без номера падает в нём с текстом
про номера позиций. Стадия пометки правок не принимает вовсе, и общий парсер
приглашал бы к обратному.
"""

from __future__ import annotations

from telegram_bot import constants
from telegram_bot.i18n import t
from telegram_bot.parsers.results import ParseError


class NotesParser:
    """Сообщение пользователя → пометка к операции."""

    @staticmethod
    def parse(raw: str | None, *, allow_empty: bool = False) -> str:
        """Пометка из присланного текста.

        `allow_empty` — по образцу `AmountParser.parse(allow_zero=True)`: у
        `/add` пустой хвост законен и означает операцию без пометки, а на стадии
        пометки пустое сообщение — промах, и убрать набранное там можно кнопкой
        «Очистить». Умолчание строгое: пустая пометка законна ровно в одном из
        двух мест, и разрешать её молча везде значило бы оставить нажатие
        «Очистить» без единственного своего смысла.

        Пробелы по краям срезаются: невидимую разницу между «обед» и «обед »
        пользователь не различит, а в листе операций она осталась бы навсегда.
        """
        text = (raw or "").strip()

        if not text:
            if allow_empty:
                return ""
            raise ParseError(t("parse.notes.empty"))

        # Перевод строки ищется до длины: сообщение в пять коротких строк
        # отказ по длине не получит, а причина отказа у него всё равно другая,
        # и назвать надо именно её.
        if "\n" in text:
            raise ParseError(t("parse.notes.multiline"))

        if len(text) > constants.NOTES_MAX_LENGTH:
            raise ParseError(
                t("parse.notes.too_long", limit=constants.NOTES_MAX_LENGTH)
            )

        return text
