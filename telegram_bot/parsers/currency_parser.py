"""Разбор валюты из слова пользователя."""

from __future__ import annotations

import unicodedata

from telegram_bot.api_client.models import Currency
from telegram_bot.i18n import t

#: Написания, которые принимаются за валюту, — на всех языках бота сразу.
#:
#: Список щедрый намеренно. Валюту в `/add` пишут каждый раз, и промах по
#: написанию стоил бы отказа на самой частой команде бота. Дешевле перечислить
#: падежи и разговорные формы один раз здесь. Все языки разом, а не язык
#: пользователя: сменивший язык продолжает писать «руб» по привычке, и
#: наказывать его за это нечем оправдать — ни одно написание не означает в
#: другом языке другую валюту.
#:
#: Написания с диакритикой и без неё перечислены оба («dólar» и «dolar»):
#: снимать диакритику общим правилом нельзя, это ломает хинди, где знаки над
#: и под буквой — часть самой буквы.
#:
#: Однобуквенные сокращения («р», «д») сюда не входят: они слишком легко
#: оказываются началом настоящей пометки.
_SPELLINGS: dict[Currency, tuple[str, ...]] = {
    Currency.RUB: (
        "rub", "rur", "₽",
        "руб", "рубли", "рубль", "рубля", "рублей",
        "ruble", "rubles", "rouble", "roubles",
        "rublo", "rublos",
        "रूबल",
    ),
    Currency.USD: (
        "usd", "$",
        "долл", "доллар", "доллары", "доллара", "долларов", "бакс", "баксы", "баксов",
        "dollar", "dollars", "buck", "bucks",
        "dólar", "dólares", "dolar", "dolares",
        "डॉलर",
    ),
    Currency.EUR: (
        "eur", "€",
        "евро", "евр",
        "euro", "euros",
        "यूरो",
    ),
    Currency.RSD: (
        "rsd",
        "дин", "динар", "динары", "динара", "динаров",
        "dinar", "dinars", "dinares",
        "दीनार",
    ),
}


def normalize(word: str) -> str:
    """Приводит слово к виду ключа словаря написаний.

    NFC — одна и та же буква с диакритикой приходит с клавиатуры то готовой, то
    составной; `casefold` — регистр, в том числе испанский и французский.
    «Ё» складывается с «е» по той же причине, по какой это делается с
    псевдонимами категорий: на телефонной клавиатуре её набирают через раз, и
    отказ из-за буквы был бы отказом ни за что.
    """
    return unicodedata.normalize("NFC", word.strip()).casefold().replace("ё", "е")


_ALIASES: dict[str, Currency] = {
    normalize(spelling): currency
    for currency, spellings in _SPELLINGS.items()
    for spelling in spellings
}


def hint() -> str:
    """Что показать, когда слово не опознано.

    По одному характерному написанию на валюту и на языке пользователя: полный
    перечень падежей в сообщении об ошибке только мешает.
    """
    return t("parse.currency.hint")


def parse(word: str) -> Currency | None:
    """Валюта по слову пользователя или `None`, если слово не опознано."""
    return _ALIASES.get(normalize(word))
