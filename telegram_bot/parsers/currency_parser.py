"""Разбор валюты из слова пользователя."""

from __future__ import annotations

from telegram_bot.api_client.models import Currency

#: Написания, которые принимаются за валюту. Ключи в нижнем регистре и без «ё».
#:
#: Список щедрый намеренно. Валюта теперь указывается в **каждой** команде
#: `/add`, то есть это самое частое слово во всём вводе, и требовать от
#: пользователя помнить ISO-код ради одной покупки хлеба значит сделать бота
#: неудобным ровно там, где им пользуются чаще всего. Дешевле перечислить
#: падежи и разговорные формы один раз здесь.
#:
#: Однобуквенные сокращения («р», «д») сюда не входят: они слишком легко
#: оказываются началом настоящей пометки.
_ALIASES: dict[str, Currency] = {
    alias: currency
    for currency, aliases in {
        Currency.RUB: (
            "rub", "rur", "руб", "рубли", "рубль", "рубля", "рублей", "₽",
        ),
        Currency.USD: (
            "usd", "долл", "доллар", "доллары", "доллара", "долларов",
            "бакс", "баксы", "баксов", "$",
        ),
        Currency.EUR: (
            "eur", "евро", "евр", "€",
        ),
        Currency.RSD: (
            "rsd", "дин", "динар", "динары", "динара", "динаров",
        ),
    }.items()
    for alias in aliases
}

#: Что показать, когда слово не опознано. По одному характерному написанию на
#: валюту: полный перечень падежей в сообщении об ошибке только мешает.
HINT = "рубли, доллары, евро, динары"


def normalize(word: str) -> str:
    """Приводит слово к виду ключа словаря написаний.

    «Ё» складывается с «е» по той же причине, по какой это делается с
    псевдонимами категорий: на телефонной клавиатуре её набирают через раз, и
    отказ из-за буквы был бы отказом ни за что.
    """
    return word.strip().lower().replace("ё", "е")


def parse(word: str) -> Currency | None:
    """Валюта по слову пользователя или `None`, если слово не опознано."""
    return _ALIASES.get(normalize(word))
