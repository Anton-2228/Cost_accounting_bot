"""Ошибки разбора сырья чека.

Все три несут готовый русский текст: разбор идёт по шагам, и каждый шаг иначе
пришлось бы оборачивать проверкой результата предыдущего. Тот же приём, что у
:class:`telegram_bot.parsers.ParseError`.

Различие между ними — в том, что пользователю делать дальше. «Возврат» и
«неожиданная форма» чинятся только удалением чека, а расхождение с итогом —
повод посмотреть на чек глазами, потому что записанная сумма разошлась бы с
бумажкой.
"""

from __future__ import annotations


class ReceiptError(Exception):
    """Из сырья чека не собрать список позиций; текст готов для пользователя."""

    def __init__(self, message: str) -> None:
        self.message = message
        super().__init__(message)


class ReceiptNotSupportedError(ReceiptError):
    """Чек есть, но такой разбор не поддерживается (например, возврат)."""


class ReceiptFormatError(ReceiptError):
    """Расшифровка неожиданной формы: нужных полей в ней нет."""


class ReceiptMismatchError(ReceiptError):
    """Сумма позиций не сошлась с итогом чека.

    Канарейка на «прочитали не то поле». Строить её на нулевой сумме нельзя:
    нулевая цена товара законна, и такая проверка молчала бы ровно там, где
    ошибка есть, и кричала бы там, где её нет.
    """
