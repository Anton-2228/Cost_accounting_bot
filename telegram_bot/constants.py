"""Неизменяемые поведенческие константы бота.

Единственный источник истины для значений, НЕ зависящих от окружения.
Параметры развёртывания задаются через окружение — см.
:mod:`telegram_bot.config` и `env/telegram_bot.env.example`.
"""

from __future__ import annotations

# ---- Значения по умолчанию для настроек ----
DEFAULT_REDIS_PORT = 6379
DEFAULT_NOTIFY_PORT = 8002
DEFAULT_API_TIMEOUT_SECONDS = 60.0

# ---- Обращение к модели ----
# Таймаут задан явно: библиотека провайдера ждёт долго, а разбор чека — диалог,
# в котором пользователь смотрит на экран. Зависший вызов в старой версии
# останавливал разбор насовсем.
DEFAULT_AI_TIMEOUT_SECONDS = 60.0
# Задача классифицирующая, а не творческая: разброс ответов тут только вредит.
DEFAULT_AI_TEMPERATURE = 0.2
# Потолок ответа. Чек из полусотни позиций даёт ответ в несколько килобайт.
AI_MAX_TOKENS = 4096

# ---- Таймауты отдельных вызовов api ----
# Создание документа: api пишет строки и ставит задачу в очередь, но пользователь
# ждёт ответа, а не готовности Google-документа — тот приедет уведомлением.
CREATE_SPREADSHEET_TIMEOUT_SECONDS = 180.0
# Просьба вчитать листы: обработка асинхронная (202), но сам запрос идёт через
# очередь задач и не должен обрываться раньше времени.
SYNC_TIMEOUT_SECONDS = 180.0
# Запись операции или перевода: одна короткая транзакция, но с постановкой
# задач в очередь перерисовки.
WRITE_TIMEOUT_SECONDS = 120.0

# ---- Разбор ввода ----
# Минимальное число позиционных аргументов. Всё после них — пометка.
#
# У команд оно разное, поэтому констант две. Раньше была одна общая: тогда
# `/add` и `/add_trans` действительно имели по три аргумента, но у операции
# появилась валюта, а у перевода — нет (сумма перевода по определению в валюте
# счёта-источника). Общая константа с этого момента означала бы для одной из
# двух команд неправду, причём молча: лишний аргумент просто уехал бы в пометку.
#: `/add сумма категория счёт валюта [пометка...]`
RECORD_ARGUMENTS = 4
#: `/add_trans сумма откуда куда [пометка...]`
TRANSFER_ARGUMENTS = 3
# Разделители дробной части, которые принимает бот. Пользователь набирает сумму
# на телефоне, где запятая под рукой, а точка — нет.
DECIMAL_SEPARATORS = (",",)
# Копейки. Повторяет `NUMERIC(14, 2)` в схеме: лишние знаки api отвергнет 422
# без внятного текста, поэтому бот объясняет это сам.
MONEY_DECIMAL_PLACES = 2

# ---- Ограничения, повторяющие серверные ----
# Дублируют `api.core.constants`, потому что бот обязан объяснить ошибку
# по-русски раньше, чем получит 422 без внятного текста.
MIN_RESET_DAY = 1
MAX_RESET_DAY = 28
NOTES_MAX_LENGTH = 512
PRODUCT_NAME_MAX_LENGTH = 255
PRODUCT_TYPE_MAX_LENGTH = 64
SPREADSHEET_TITLE_MAX_LENGTH = 255
EMAIL_MAX_LENGTH = 320
TIMEZONE_MAX_LENGTH = 64

# ---- Значения по умолчанию для мастера создания таблицы ----
DEFAULT_TIMEZONE = "Europe/Moscow"

# ---- Разбор чека ----
# Категория-корзина: туда уходит позиция, которой не нашлось категории.
# Повторяет `api.core.constants.DEFAULT_EXPENSE_CATEGORY`: бот называет её в
# промпте и подставляет по названию, а не по идентификатору.
DEFAULT_EXPENSE_CATEGORY = "НеопределенныеТраты"
# Разделитель между номерами позиций и значением в строке правки:
# «1,3 - молочка».
CHECK_EDIT_SEPARATOR = "-"
# Разделители номеров позиций внутри одной правки.
CHECK_NUMBER_SEPARATORS = (",", " ")
# Копейки в суммах ФНС: ответ внешнего сервиса целочисленный.
KOPECKS_IN_RUBLE = 100
# Вид расчёта «приход». Возвраты и расходы кассы разбор не поддерживает: у них
# другой знак и другой смысл, и записать их как покупку значило бы соврать.
RECEIPT_OPERATION_INCOME = 1
# Название позиции, у которой его нет. Пустое имя api не примет, а сумма у такой
# позиции всё равно настоящая и в итог чека входит.
UNNAMED_PRODUCT = "Без названия"
# Форматы поля `t` QR-строки ФНС. Вариант без секунд стоит **первым**:
# `strptime` разрешает полям быть короче двух цифр, и `20260725T1507` по шаблону
# с секундами разбирается как 15:00:07 — молча и правдоподобно.
RECEIPT_DATETIME_FORMATS = ("%Y%m%dT%H%M", "%Y%m%dT%H%M%S")
