#: Потолок Google на содержимое одной ячейки. Чек, не влезающий в него,
#: обрезается с пометкой: отказ Google на слишком длинном значении — 400, то
#: есть терминальная ошибка, и лист встал бы навсегда из-за одной закупки.
CELL_TEXT_LIMIT = 50_000
#: Хвост, который дописывается к обрезанному чеку. `{check_id}` подставляется:
#: обрезка ломает JSON, и единственное, что делает ячейку полезной — указание,
#: где лежит целое.
CHECK_TRUNCATED_SUFFIX = "…обрезано, полный чек в базе, id={check_id}"
#: Подписи итоговых строк листа статистики.
TOTAL_INCOME_TITLE = "Общие доходы"
TOTAL_EXPENSE_TITLE = "Общие расходы"

# ---- Валюты ----
#: Содержимое выпадающего списка в колонке `Currency` листа счетов.
#:
#: **Зеркало** перечисления `api.enums.Currency` — так же, как ширины листов
#: здесь зеркалят `api.validation`. Ходить за списком в api ради значений,
#: меняющихся только вместе с миграцией, значило бы поставить создание листа в
#: зависимость от лишнего запроса. Расхождение ловится тестом.
