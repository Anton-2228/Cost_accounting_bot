#: С какой строки начинаются данные (1-based, как в A1).
FIRST_DATA_ROW = 2

# ---- Отображение ----
#: Подпись перевода в колонке `Category` листа операций. Отдельного адресата
#: перерисовки для переводов нет: в реестре это обычная строка.
TRANSFER_CATEGORY_TITLE = "Перевод"
#: Разделитель счетов в колонке `Source` строки перевода: «Кошелёк → Карта».
