GRID_ROW_CHUNK = 200
#: Сколько строк создаётся у нового листа. Данные приходят при первой же
#: перерисовке, и лист почти всегда сразу дорастает до нужного размера.
GRID_INITIAL_ROWS = 200
#: Пустые колонки справа от системных. Сетка точного размера не оставляла
#: пользователю ни одной ячейки под собственную формулу: писать в системные
#: колонки бессмысленно — перерисовка строит лист целиком и затрёт написанное.
SPARE_COLUMN_COUNT = 10
