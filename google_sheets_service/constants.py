# ---- Локаль документа ----
#: Локаль влияет на разбор введённых пользователем чисел: «1 000,50» становится
#: числом только в русской локали. Записываем мы типизированные значения, а
#: читаем `UNFORMATTED_VALUE`, поэтому разбирать строки не приходится вовсе.
