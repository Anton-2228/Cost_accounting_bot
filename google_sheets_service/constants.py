#: Валюта, к которой сведён лист статистики. Зеркало
#: `api.core.constants.STATISTICS_CURRENCY` по той же причине: здесь она нужна
#: только для подписи колонки.
STATISTICS_CURRENCY = "EUR"

# ---- Метка документа в Drive ----
#: Ключ `appProperties`, которым помечается созданный документ. По нему сервис
