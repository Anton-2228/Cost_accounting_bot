"""Неизменяемые поведенческие константы сервиса.

Разделение то же, что в :mod:`api.core.constants`: сюда попадает всё, что не
зависит от окружения, а параметры развёртывания живут в
:mod:`checks_service.config`.
"""

from __future__ import annotations

# ---- Авторизация Mini App ----
#: Схема заголовка `Authorization`, принятая для данных Telegram Mini App.
#: `Authorization: tma <initData>`.
AUTH_SCHEME = "tma"
#: Ключ, которым Telegram выводит секрет подписи из токена бота.
#: `secret = HMAC_SHA256(key="WebAppData", msg=<токен бота>)`, и порядок
#: аргументов здесь обратный привычному: ключом служит константа, сообщением —
#: токен. Перепутать их значит получить подпись, которая никогда не сойдётся.
INIT_DATA_SECRET_KEY = b"WebAppData"
#: Поле `initData`, несущее подпись остальных полей.
INIT_DATA_HASH_FIELD = "hash"
#: Поле с временем выдачи. Проверка возраста нужна потому, что подпись сама по
#: себе бессрочна: перехваченная строка иначе работала бы вечно.
INIT_DATA_AUTH_DATE_FIELD = "auth_date"
#: Поле с JSON-описанием пользователя.
INIT_DATA_USER_FIELD = "user"

# ---- Формат ФНС (Россия) ----
#: Ответ proverkacheka.com с этим кодом означает успех.
PROVERKACHEKA_SUCCESS_CODE = 1
#: Коды, означающие «такого чека нет». Это не сбой сервиса: повтор даст тот же
#: ответ, и пользователю надо сказать об этом прямо, а не предлагать «попробуйте
#: ещё раз».
PROVERKACHEKA_NOT_FOUND_CODES = frozenset({0, 2, 3, 4, 5})
#: Разделитель составного ключа дедупликации ФНС: «ФН:ФД:ФП».
RU_FNS_KEY_SEPARATOR = ":"
#: Форматы времени в поле `t` QR-строки: с секундами и без них. Оба встречаются
#: на реальных чеках, поэтому разбираются оба.
#:
#: **Порядок существенен.** `strptime` разрешает однозначным полям быть короче
#: двух цифр, поэтому «1507» по шаблону с секундами разбирается как 15:00:07 —
#: молча и правдоподобно. Вариант без секунд стоит первым, а лишние «30» на
#: конце он не съест и честно уступит второму.
RU_FNS_DATETIME_FORMATS = ("%Y%m%dT%H%M", "%Y%m%dT%H%M%S")

# ---- Формат SUF (Сербия) ----
#: Единственный хост, чьи ссылки считаются сербским чеком. Той же программой
#: (TaxCore) пользуются и другие страны, но проверен только этот инстанс, и
#: молча пытаться разобрать черногорский чек значило бы выдать догадку за
#: поддержку формата.
SRB_SUF_HOST = "suf.purs.gov.rs"
#: Схема, по которой сервис ходит за расшифровкой. Всегда `https`, чем бы касса
#: ни напечатала ссылку.
SRB_SUF_SCHEME = "https"
#: Схемы, при которых строка считается ссылкой на чек. `http` здесь потому, что
#: печатает её касса, а не мы: отвергнув его, мы сказали бы «это не чек» про
#: настоящий чек. Ходить открытым текстом это не заставляет — ссылка для
#: запроса нормализуется к `https`.
SRB_SUF_SCHEMES = frozenset({"https", "http"})
#: Параметр ссылки, несущий чек целиком в base64.
SRB_SUF_QUERY_FIELD = "vl"
#: Путь, по которому отдаются позиции чека. В HTML-странице их нет: она грузит
#: их отдельным запросом, и мы делаем ровно то же.
SRB_SUF_SPECIFICATIONS_PATH = "/specifications"
#: Кука, которой сайт выбирает язык страницы. Ни `Accept-Language`, ни параметр
#: запроса на неё не влияют — проверено, оба игнорируются.
SRB_SUF_LOCALE_COOKIE = "localization"
#: Сербская (кириллица) и английская версии — единственные два языка сайта.
#: Латиницы в его списке нет вовсе.
SRB_SUF_LOCALE_SR = "sr-Cyrl-RS"
SRB_SUF_LOCALE_EN = "en-US"

#: Разбор двоичного заголовка из `vl`. Все поля лежат до `SRB_SUF_HEADER_SIZE`,
#: поэтому необязательный идентификатор покупателя, который стоит дальше, ни
#: одно из них не сдвигает.
#:
#: **Порядок байт у суммы и у времени разный** — это не опечатка и не ошибка
#: чтения: сумма записана little-endian, время big-endian. Проверено сверкой с
#: тем, что показывает сама страница чека.
SRB_SUF_VERSION_OFFSET = 0
SRB_SUF_REQUESTED_BY_SLICE = slice(1, 9)
SRB_SUF_SIGNED_BY_SLICE = slice(9, 17)
SRB_SUF_TOTAL_COUNTER_SLICE = slice(17, 21)
SRB_SUF_TX_COUNTER_SLICE = slice(21, 25)
SRB_SUF_TOTAL_AMOUNT_SLICE = slice(25, 33)
SRB_SUF_DATE_TIME_SLICE = slice(33, 41)
#: Столько байт обязано декодироваться из `vl`, иначе это не чек.
SRB_SUF_HEADER_SIZE = 41
#: Сумма записана в десятитысячных долях динара.
SRB_SUF_AMOUNT_SCALE = 10_000
#: Разделитель номера чека: «Затражио-Потписао-Бројач».
SRB_SUF_KEY_SEPARATOR = "-"

#: Значение поля «Врста», означающее обычную продажу. Всё остальное
#: (`Рефундација`, авансы) разбор отвергает — но уже в боте, а не здесь: чек
#: сохраняется любой, интерпретирует его разбор.
SRB_SUF_INVOICE_TYPE_NORMAL = "Промет"
